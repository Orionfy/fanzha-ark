def render_ending(ending_data):
    """CLI 渲染结局（供 game.py 调用）"""
    print("\n" + "=" * 50)
    slow_type(f"【{ending_data['title']}】")
    for p in ending_data["paragraphs"]:
        slow_type(p)
    print(colored(f"🏆 解锁成就：{ending_data['achievement']}", "yellow"))
    print("=" * 50)
